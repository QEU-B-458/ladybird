static String wasm_type(BridgeArgument const& argument)
{
    switch (argument.type) {
    case BridgeValueType::EntityId:
        return "i32"_string;
    case BridgeValueType::Boolean:
        return "i32"_string;
    case BridgeValueType::Number:
        return "f32"_string;
    case BridgeValueType::String:
        return "ptr, len"_string;
    case BridgeValueType::Void:
        return "void"_string;
    case BridgeValueType::Float32Array:
        return "ptr"_string;
    }
    VERIFY_NOT_REACHED();
}

static String wasm_return_type(BridgeValueType type)
{
    switch (type) {
    case BridgeValueType::Void:
        return "void"_string;
    case BridgeValueType::EntityId:
    case BridgeValueType::Boolean:
        return "i32"_string;
    case BridgeValueType::Number:
        return "f64"_string;
    case BridgeValueType::String:
        return "ptr, len"_string;
    case BridgeValueType::Float32Array:
        return "ptr"_string;
    }
    VERIFY_NOT_REACHED();
}

static ErrorOr<String> generate_wasm_imports()
{
    StringBuilder builder;
    builder.append("# MyceliumVR WASM Imports\n\n"sv);
    builder.append("This file is generated by MyceliumVR from the native BridgeRegistry.\n\n"sv);
    builder.append("| Module | Import | Parameters | Result | Notes |\n"sv);
    builder.append("| --- | --- | --- | --- | --- |\n"sv);
    for (auto const& function : BridgeRegistry::the().functions()) {
        if (!function.wasm_exposed)
            continue;
        builder.appendff("| mycelium | {} | ", function.name);
        if (function.arguments.is_empty()) {
            builder.append("none"sv);
        } else {
            for (size_t i = 0; i < function.arguments.size(); ++i) {
                if (i > 0)
                    builder.append(", "sv);
                builder.append(wasm_type(function.arguments[i]));
            }
        }
        builder.appendff(" | {} | {}", wasm_return_type(function.return_type), function.description);
        if (function.hot_path)
            builder.append(" Hot path."sv);
        builder.append(" |\n"sv);
    }
    return builder.to_string();
}

static ErrorOr<String> generate_api_json()
{
    StringBuilder builder;
    builder.append("{\n"sv);
    builder.append("  \"apiName\": \"mycelium\",\n"sv);
    builder.append("  \"sdkName\": \"Mycelium\",\n"sv);
    builder.append("  \"functions\": [\n"sv);
    auto const& functions = BridgeRegistry::the().functions();
    for (size_t i = 0; i < functions.size(); ++i) {
        auto const& function = functions[i];
        builder.append("    {\n"sv);
        builder.appendff("      \"module\": \"{}\",\n", function.module);
        builder.appendff("      \"jsNamespace\": \"{}\",\n", function.js_namespace);
        builder.appendff("      \"name\": \"{}\",\n", function.name);
        builder.appendff("      \"description\": \"{}\",\n", function.description);
        builder.appendff("      \"returnType\": \"{}\",\n", bridge_value_type_name(function.return_type));
        builder.appendff("      \"hotPath\": {},\n", function.hot_path ? "true"sv : "false"sv);
        builder.append("      \"args\": ["sv);
        for (size_t argument_index = 0; argument_index < function.arguments.size(); ++argument_index) {
            auto const& argument = function.arguments[argument_index];
            if (argument_index > 0)
                builder.append(", "sv);
            builder.appendff("{{ \"name\": \"{}\", \"type\": \"{}\" }}", argument.name, bridge_value_type_name(argument.type));
        }
        builder.append("]\n"sv);
        builder.append("    }"sv);
        if (i + 1 < functions.size())
            builder.append(","sv);
        builder.append("\n"sv);
    }
    builder.append("  ]\n"sv);
    builder.append("}\n"sv);
    return builder.to_string();
}

ErrorOr<void> generate_sdk(StringView target, StringView output_directory)
{
    auto normalized_target = target.is_empty() ? "all"sv : target;

    auto write_typescript = normalized_target == "all"sv || normalized_target == "typescript"sv || normalized_target == "ts"sv;
    auto write_javascript = normalized_target == "all"sv || normalized_target == "javascript"sv || normalized_target == "js"sv;
    auto write_wasm = normalized_target == "all"sv || normalized_target == "wasm"sv;
    auto write_json = normalized_target == "all"sv || normalized_target == "json"sv || normalized_target == "api-json"sv;

    if (!write_typescript && !write_javascript && !write_wasm && !write_json)
        return Error::from_string_literal("Unknown SDK target. Use all, typescript, javascript, wasm, or json.");

    if (write_typescript)
        TRY(write_text_file(sdk_path(output_directory, "mycelium.d.ts"sv), TRY(generate_typescript_declarations())));
    if (write_javascript)
        TRY(write_text_file(sdk_path(output_directory, "mycelium.js"sv), TRY(generate_javascript_wrapper())));
    if (write_wasm)
        TRY(write_text_file(sdk_path(output_directory, "wasm-imports.md"sv), TRY(generate_wasm_imports())));
    if (write_json)
        TRY(write_text_file(sdk_path(output_directory, "mycelium-api.json"sv), TRY(generate_api_json())));

    return {};
}

