    builder.append("    destroy() {\n      return mycelium.destroyEntity(id);\n    },\n\n"sv);
    builder.append("    setTransform(transform) {\n"sv);
    builder.append("      mycelium.setTransform(\n"sv);
    builder.append("        id,\n        transform.px,\n        transform.py,\n        transform.pz,\n"sv);
    builder.append("        transform.qx ?? 0,\n        transform.qy ?? 0,\n        transform.qz ?? 0,\n        transform.qw ?? 1,\n"sv);
