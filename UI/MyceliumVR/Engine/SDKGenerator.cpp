    builder.append("  createPanel(url: string, width: number, height: number): this;\n"sv);
    builder.append("}\n\n"sv);
    builder.append("export interface MyceliumSDK {\n"sv);
    builder.append("  readonly native: MyceliumNative;\n"sv);
    builder.append("  readonly api: MyceliumApi;\n\n"sv);
    builder.append("  readonly fs: MyceliumFileSystem;\n\n"sv);
    builder.append("  log(message: string): void;\n"sv);
    builder.append("  spawnEntity(): EntityHandle;\n"sv);
    builder.append("  entityCount(): number;\n"sv);
    builder.append("  dirtyTransformCount(): number;\n"sv);
    builder.append("  acquireTransformBuffer(capacity: number): Float32Array;\n"sv);
