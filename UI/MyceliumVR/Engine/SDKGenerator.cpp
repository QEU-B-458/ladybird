static ErrorOr<void> write_text_file(StringView path, StringView text)
{
    auto file = TRY(Core::File::open(path, Core::File::OpenMode::Write | Core::File::OpenMode::Truncate));
    TRY(file->write_until_depleted(text.bytes()));
    return {};
}

static String sdk_path(StringView output_directory, StringView filename)
{
    return MUST(String::formatted("{}/{}", output_directory.trim("/"sv, TrimMode::Right), filename));
}

static String ts_type(BridgeValueType type)
{
    switch (type) {
    case BridgeValueType::Void:
        return "void"_string;
    case BridgeValueType::Boolean:
        return "boolean"_string;
    case BridgeValueType::Number:
        return "number"_string;
    case BridgeValueType::String:
        return "string"_string;
    case BridgeValueType::EntityId:
        return "EntityId"_string;
    case BridgeValueType::Float32Array:
        return "Float32Array"_string;
    }
    VERIFY_NOT_REACHED();
}

static void append_generated_header(StringBuilder& builder)
{
    builder.append("// This file is generated by MyceliumVR.\n"sv);
    builder.append("// Do not edit by hand. Update the native BridgeRegistry instead.\n\n"sv);
}

